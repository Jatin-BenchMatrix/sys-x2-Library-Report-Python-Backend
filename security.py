"""Auth + per-request tenant DB resolution.

Mirrors the Go middleware:
  - middleware/TokenFilter.go            (non-tenant: validate JWT when VERIFY_TOKEN)
  - middleware/TenantMiddleware.go       (tenant: JWT -> master DB -> tenant DSN)
  - controller/db.go (openDB)            (pick tenant vs default connection)

Exposed as a FastAPI dependency `get_request_context`, which yields a live DB
connection (closed after the request) plus the decoded JWT claims.
"""
from dataclasses import dataclass, field
from typing import Optional

import jwt
from fastapi import Header, HTTPException

from config import config
from db import open_default_db, open_master_db, open_tenant_db


@dataclass
class RequestContext:
    conn: object                      # live pymysql connection for this request
    claims: dict = field(default_factory=dict)
    tenant_id: Optional[str] = None
    user_id: Optional[str] = None     # JWT "userId" claim — for "generated by" later


def _bearer_token(authorization: Optional[str]) -> str:
    if not authorization:
        raise HTTPException(status_code=401, detail="Token is missing")
    if authorization.lower().startswith("bearer "):
        return authorization[7:].strip()
    return authorization.strip()


def _decode(token: str) -> dict:
    try:
        return jwt.decode(token, config.jwt_secret_key, algorithms=["HS256"])
    except jwt.PyJWTError:
        raise HTTPException(status_code=401, detail="Invalid or expired token")


def _as_str(value) -> Optional[str]:
    if value is None:
        return None
    if isinstance(value, float):      # JWT numeric claims arrive as float/int
        return str(int(value))
    return str(value)


def get_request_context(authorization: Optional[str] = Header(default=None)):
    """FastAPI dependency. Resolves the connection the same way Go's openDB does."""
    claims: dict = {}

    # Validate the token when tenant mode or VERIFY_TOKEN is on (TokenFilter parity).
    if config.tenant or config.verify_token:
        claims = _decode(_bearer_token(authorization))

    user_id = _as_str(claims.get("userId"))

    # --- Non-tenant: default DB (CLIENT1DB_*) ---
    if not config.tenant:
        conn = open_default_db()
        try:
            yield RequestContext(conn=conn, claims=claims, user_id=user_id)
        finally:
            conn.close()
        return

    # --- Tenant mode: JWT tenantID -> master DB -> tenant connection ---
    tenant_id = _as_str(claims.get("tenantID"))
    if not tenant_id:
        raise HTTPException(status_code=400, detail="tenantID not found in token claims")

    master = open_master_db()
    try:
        with master.cursor() as cur:
            cur.execute(
                "SELECT tenant_id, tenant_name, tenant_connection "
                "FROM config_tenant WHERE tenant_id = %s",
                (tenant_id,),
            )
            row = cur.fetchone()
    finally:
        master.close()

    if not row:
        raise HTTPException(status_code=401, detail="Invalid tenant ID")

    conn = open_tenant_db(row["tenant_connection"])
    try:
        yield RequestContext(
            conn=conn, claims=claims, tenant_id=str(row["tenant_id"]), user_id=user_id
        )
    finally:
        conn.close()
